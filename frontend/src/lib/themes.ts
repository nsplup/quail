/* 字体回退链默认值：用户输入去重后追加到链尾 */
export const EDITOR_FONT_FALLBACK = "monospace";
export const PREVIEW_FONT_FALLBACK = "sans-serif";

/**
 * 构建字体族链：输入按逗号拆分去重（保序），
 * 回退默认值追加在链尾（已包含的族不重复）。
 */
export function buildFontChain(input: string, fallback: string): string {
  const parts = [
    ...new Set(
      input
        .split(",")
        .map((p) => p.trim())
        .filter(Boolean)
    ),
  ];
  const tail = fallback
    .split(",")
    .map((p) => p.trim())
    .filter((p) => p && !parts.includes(p));
  return [...parts, ...tail].join(", ");
}

/** 把主题变量 + 字体字号写入根元素（脚本注入，替代 CSS 预定义） */
export function applyThemeVars(
  el: HTMLElement,
    id: ThemeId,
  fontEditor: string,
  fontPreview: string,
  fontSizeEditor: number,
  fontSizePreview: number
): void {
  const vars = getTheme(id).vars;
  for (const [k, v] of Object.entries(vars)) el.style.setProperty(k, v);
  el.style.setProperty("--ed-font-family", fontEditor);
  el.style.setProperty("--pv-font-family", fontPreview);
  el.style.setProperty("--ed-font-size", `${fontSizeEditor}px`);
  el.style.setProperty("--pv-font-size", `${fontSizePreview}px`);
  el.dataset.theme = id;
}
